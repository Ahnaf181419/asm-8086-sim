;Write an assembly code to store the largest of two numbers in BX 
;We will declare 3 variables num1, num2 (16 bits)

;LOGIC
;IF NUM1 > NUM2; LARGEST = NUM1
;ELSE LARGEST = NUM2

.MODEL SMALL
.STACK 100H
.DATA
NUM1 DW 450
NUM2 DW 373
.CODE
MAIN PROC

;DATA SEGMENT INITIALIZATION
MOV AX, @DATA
MOV DS, AX

;WE CAN NOT DIRECTLY COMPARE TWO MEMORY VARIABLES
;SO WE WILL USE REGISTERS FOR ONE NUMBER
;WE WANT TO CHECK WHETHER NUM1 IS THE LARGEST

;WE ARE STORING THE VALUE OF NUM1 INTO BX
;IF BX IS ALREADY GREATER, NO NEED TO CHANGE ANYTHING
;ELSE UPDATE THE VALUE OF BX WITH NUM2
MOV BX, NUM1
CMP BX, NUM2
JLE CHANGE_LARGEST
JMP END_

CHANGE_LARGEST:
MOV BX, NUM2

MAIN ENDP
END_:
MOV AH, 4CH
INT 21H
END MAIN