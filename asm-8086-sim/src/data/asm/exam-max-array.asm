.MODEL SMALL
.STACK 100H
.DATA
    ARR DW 34H, 89H, 12H, 9AH, 45H, 77H
    LEN DW 6
    MAX_VAL DW ?
.CODE
MAIN PROC
    MOV AX, @DATA
    MOV DS, AX

    MOV CX, LEN
    DEC CX
    XOR SI, SI
    MOV AX, ARR[SI]

MAX_LOOP:
    ADD SI, 2
    CMP ARR[SI], AX
    JLE SKIP
    MOV AX, ARR[SI]
SKIP:
    LOOP MAX_LOOP

    MOV MAX_VAL, AX
    MOV BX, AX

    MOV AH, 4CH
    INT 21H
MAIN ENDP
END MAIN
