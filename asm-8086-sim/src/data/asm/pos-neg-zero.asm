;Suppose a 8 bit number is stored in BL register
;Write an assembly code to check whether the number is positive,
;negative or zero and print corresponding message

;What will be the logic here?
;We will compare the value of BL with 0
;if > 0, positive
;if = 0, zero
;if < 0, negative

;Also we need to declare the messages in data segment

.MODEL SMALL
.STACK 100H

.DATA
;DECLARE THE MESSAGES
MSG_POS DB  "POSITIVE!$"
MSG_NEG DB  "NEGATIVE!$"
MSG_ZERO DB "ZERO!$"

.CODE
MAIN PROC
;DATA SEGMENT INITIALIZATION
MOV AX, @DATA
MOV DS, AX


;HERE WE DO NOT HAVE TO DO ANYTHING WITH AX APART FROM PRINTING THE MESSAGE
;SO WE CAN INITIALIZE AH WITH 9 INITIALLY
MOV AH, 9

;THE VALUE TO BE CHECKED
MOV BL, 5     

;WE WILL USE CMP INSTRUCTION HERE
;SO BASICALLY IT'S PERFORMING BL - 0 AND STORING THE RESULTS IN FLAGS
;UNLIKE SUBTRACTION, IT DOESN'T STORE THE RESULT IN THE DESTINATION
CMP BL, 0
;IF BL > 0, WE WILL USE GREATER THAN FLAG     
;IF GREATER THAN CONDITION IS TRUE, WE WILL JMP TO THE LABEL PRINT_POSITIVE
;THE SAME APPROACH FOR NEGATIVE AND ZERO
JG PRINT_POSITIVE
JE PRINT_ZERO
JL PRINT_NEGATIVE

;AH ALREADY HAS 9 IN IT, SO WE NOT NEED TO MOVE 9 TO AH HERE
;DX WILL LOAD THE EFFECTIVE ADDRESS OF THE MESSAGE WE WANT TO PRINT
;INTERRUPT WILL SHOW THE OUTPUT

PRINT_POSITIVE:
LEA DX, MSG_POS
INT 21H
;NOW, GIVE IT A THOUGHT   

;HERE STATEMENTS ARE GETTING EXECUTED LINE BY LINE
;AFTER PRINTING THE MSG OF POSITIVE, DO WE WANT TO PRINT THE OTHERS MESSAGES TOO?
;OR DO WE WANT TO EXIT THE PROGRAM?

;SO, WE NEED TO MOVE TO THE END_ LABEL
;HERE, WE WILL USE UNCONDITIONAL JUMP
JMP END_ ;IT WILL JMP TO LABEL END_;PROGRAM CONTROL WILL BE RETURNED TO DOS

PRINT_ZERO:
LEA DX, MSG_ZERO
INT 21H 
JMP END_

PRINT_NEGATIVE:
LEA DX, MSG_NEG
INT 21H                                                                         
;SINCE THERE ARE NO MORE LINES TO BE EXECUTED, IT'S OK IF WE DO NOT USE JMP HERE
  
MAIN ENDP

;RETURN TO DOS
END_:
MOV AH, 4CH
INT 21H
END MAIN  




;CHANGE THE VALUE OF BL TO A NEGATIVE VALUE OR ZERO VALUE 
;USING SINGLE STEP, YOU CAN CHECK WHICH CONDITION IS GETTING EXECUTED