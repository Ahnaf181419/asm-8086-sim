.MODEL SMALL
.STACK 100H
.DATA
NEW_LINE DB 0AH,0DH,'$' 
W DB 1,2,3,4,5   
SUM DB 0
W_END DB LABEL BYTE
W_SIZE EQU W_END - W
.CODE
MAIN PROC
MOV AX, @DATA
MOV DS, AX

;---------BYTE ARRAY-----------;
MOV CX, 5
XOR AX, AX
LEA SI, W

PRINT:
MOV AL,[SI]
CALL OUTDEC;AH = 0, AL = 2 
INC SI 

PUSH AX ;AH = 0; AL = 1    
MOV AH, 9
LEA DX, NEW_LINE
INT 21H
POP AX  ;AH = 0; AL = 1 
LOOP PRINT 

LEA SI, W
MOV CX, 5
XOR AX, AX

SUM_:
ADD AL, [SI] 
INC SI
LOOP SUM_

CALL OUTDEC 


END_:
MOV AH, 4CH
INT 21H
MAIN ENDP
INCLUDE INDEC.ASM
INCLUDE OUTDEC.ASM
END MAIN


