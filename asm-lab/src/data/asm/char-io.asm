;================================================================
;Take a single character as input and display it in the next line   

;Please remember while dealing with input or output,we always need 
;to generate an interrupt (INT 21h)!!
;================================================================
.MODEL SMALL
.STACK 100H
.DATA

.CODE  
MAIN PROC 
    
;DATA SEGMENT INITIALIZATION
MOV AX, @DATA
MOV DS, AX

;USER INPUT
;NEED TO MOVE 1 TO AH
MOV AH,1
INT 21H
;ASCII VALUE OF THE INPUT WILL BE STORED IN AL
MOV BL, AL ; WE ARE STORING THE DATA IN BL AS WE WILL WORK WITH OUTPUT MULTIPLE TIMES
           ; AL VALUE MAY BE CHANGED IN THE LATER INT 21H CALLS


;DISPLAY A NEW LINE
;TO GET NEW LINE, WE NEED TO PRINT NEW LINE AND CARRIAGE RETURN'S ASCII VALUE   


;TO DISPLAY A SINGLE CHARACTER AS OUTPUT, 2 NEEDS TO BE MOVED TO AH
;THE CHARACTER TO DISPLAY MUST BE STORED IN DL
;DOS TREATS THE VALUE IN DL AS AN ASCII CODE
;SO IF DL = 32H, "2" WILL BE DISPLAYED (ASCII 32H = "2")
;SIMILARLY, IF DL = 41H, "A" WILL BE DISPLAYED (ASCII 41H = "A")


MOV AH,2
MOV DL, 0AH; ASCII VALUE OF NEWLINE 
INT 21H
MOV DL, 0DH; ASCII VALUE OF CRET
INT 21H



;SAME PROCESS TO DISPLAY THE OUTPUT
MOV AH, 2
MOV DL, BL
INT 21H

MAIN ENDP

MOV AH, 4CH
INT 21H
END MAIN